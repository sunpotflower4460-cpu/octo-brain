// 繊細な相談の検出と、統合脳への「寄り添い方」の指示(LLM を使わない決定的な判定)。
// - crisis           : 希死念慮・自傷がにじむ相談
// - medical_emergency: 命に関わる急病の可能性がある症状
// 危険だと判定して案内だけを出すと「話を聞いてもらえなかった」と感じさせる。まず人として
// 向き合い、案内は自然な選択肢として添える。検出語はアプリ側(web/src/lib/crisis.ts)と揃える。

// - crisis           : 危機(方法を求める・具体的な計画や手段・自傷・自殺の言及)。窓口を案内する
// - distress         : つらさの吐露(「マジ辛くて消えたい」など)。話を聴くことに徹し、窓口は控えめに
// - medical_emergency: 命に関わる急病の可能性がある症状
// - venting          : 死や消滅を口にしない、疲れ・限界の短い吐露(「もう無理、疲れた」)。聴くことに徹する
export type CareKind = "crisis" | "distress" | "venting" | "medical_emergency";

// 危機: 方法・手段・計画・行為・切迫
const CRISIS: RegExp[] = [
  /自殺|自死|首を吊|首をつ|飛び降り|とびおり|練炭|OD(する|した|しよう)|オーバードーズ|遺書/,
  /リスカ|リストカット|自傷|自分を傷つけ|手首を切/,
  /(死ぬ|死ねる|消える|楽になれる|楽に死ねる)方法|楽に死/,
  /(死にたい|消えたい|死のう|終わりにしたい).{0,20}(計画|準備|薬を(貯め|ためて)|ロープ|今夜|今日|今から|本気|決めた)/,
  /(計画|準備|薬を(貯め|ためて)|ロープ|今夜|今から|本気|決めた).{0,20}(死にたい|死ぬ|死のう|消える)/,
  /suicid|kill myself|end my life|self[- ]?harm|how to die/i,
];

// つらさの吐露: 死や消滅を口にするが、方法や計画・行為は伴わない
const DISTRESS: RegExp[] = [
  /死にたい|しにたい|死のう|死んでしまいたい|消えたい|きえたい|消えてしまいたい|いなくなりたい/,
  /(全部|すべて|人生|何もかも|もう).{0,6}終わりにしたい|もう楽になりたい|生きるのが(つらい|辛い|しんどい|疲れた)|生きることに疲れ/,
  /生きていたくない|生きる意味がない|生きてる意味がない/,
  /want to die|want to disappear/i,
];

// 疲れ・限界の吐露。相談の形(〜すべき? どうすれば?)をとっていない短い入力だけを対象にする
// (「仕事に疲れた。転職すべき?」は通常の相談として8視点で答える)
const VENTING = /もう無理|疲れた|疲れ果て|限界|しんどい|投げ出したい|逃げ出したい|心が折れ|つらすぎ|辛すぎ|泣きたい/;
const CONSULT = /べき|どう(すれば|したら|する)|[?？]|迷って|教えて|方法/;
const VENTING_MAX_LEN = 60;

const MEDICAL_EMERGENCY: RegExp[] = [
  /胸.{0,8}(締め付け|しめつけ|圧迫|激しく痛|強く痛)/,
  /(意識がない|意識が(ない|戻らない|もうろう)|呼びかけに反応しない|呼吸(をして|し)ていない|息をしていない)/,
  /(顔の片側|片側の(手足|腕|顔)).{0,8}(動かない|しびれ|麻痺|下が)|ろれつが回らない/,
  /(大量に|止まらない).{0,4}出血|血が止まらない|けいれん(が止まらない|している)/,
  /chest pain|can'?t breathe|not breathing|unconscious/i,
];

export function detectCare(input: string): CareKind | null {
  if (CRISIS.some((p) => p.test(input))) return "crisis";
  if (DISTRESS.some((p) => p.test(input))) return "distress";
  if (input.length <= VENTING_MAX_LEN && VENTING.test(input) && !CONSULT.test(input)) return "venting";
  if (MEDICAL_EMERGENCY.some((p) => p.test(input))) return "medical_emergency";
  return null;
}

// 窓口を案内してよいか(アプリのカード表示にも使う)。
// - crisis は常に案内する
// - distress は、同じ会話で2回目以降(careTurns>=1)か、統合脳が深刻と判断して本文で窓口に触れたとき
export function shouldOfferSupport(kind: CareKind | null, careTurns: number, answer: string): boolean {
  if (kind === "crisis") return true;
  if (kind !== "distress") return false;
  return careTurns >= 1 || /0120-?279-?338|いのちの電話|よりそいホットライン|相談窓口/.test(answer);
}

// 統合脳・深化・共鳴の user メッセージに添える指示。
export function careDirective(kind: CareKind | null, careTurns = 0): string | null {
  switch (kind) {
    case "venting":
      return `[寄り添いモード・吐露]
疲れや限界の短い吐露。死や自傷の示唆はない。分析や助言より先に、まず受け止めて話を聴く。
- 相談文を「」で引用して書き出さない。自分の言葉で語りかけて始める
- 危機として扱わない。死にたい気持ちや危険の確認、相談窓口・119番の案内から入らない(本文に死や自傷の示唆が出てきたときだけ、柔らかく確かめる)
- 責めない、説教しない、「〜すべき」を並べない、安易に励まさない、解決策を急がない
- 軸・緊張・視点・腕などの分析の言葉は使わない
- 何があったのかを、話せるところから聞かせてほしいと穏やかに伝え、開かれた問いで終える。250字程度`;
    case "distress":
      return careTurns >= 1
        ? `[寄り添いモード・継続]
この会話で、つらさや「消えたい」気持ちを打ち明けるのは初めてではない。引き続き、分析より先に話を聴くことに徹する。
- 相談文を「」で引用して書き出さない。前に聞いた内容も踏まえ、今回の言葉を受け止めて言葉にする
- 責めない、説教しない、「〜すべき」を並べない、安易に励まさない
- 本文の終わり近くで一度だけ、押しつけずに「ここで話し続けてもいいし、声で話せる場所もある」と選択肢を添えてよい(よりそいホットライン 0120-279-338 は24時間・無料)。繰り返し勧めない
- 方法・計画・手段・今すぐの危険がうかがえるときだけは、窓口と119番をはっきり伝える
- 方法や手段の情報は出さない。軸・緊張・視点・腕などの分析の言葉、見出し、太字は使わない
- 最後は、続きを話してもらえる開かれた問いで終える。400字程度`
        : `[寄り添いモード・聴く]
つらさや「消えたい」気持ちの吐露がある。まだ「話を聞いてほしい」段階かもしれない。窓口を案内するより、まず話を聴くことに徹する。
- 相談文を「」で引用して書き出さない。自分の言葉で語りかけて始める
- 相手の言葉を受け止め、その奥にあるつらさを、決めつけずに言葉にする。打ち明けてくれたことを大切に受け取る
- 責めない、説教しない、「〜すべき」を並べない、安易に励まさない。分析や解決策を急がない
- 相談窓口や119番は、原則として出さない(軽い吐露に毎回案内を出すと、話しにくくさせてしまう)。ただし、方法・計画・手段・今すぐの危険・長く続く強い希死念慮がうかがえ、あなたが「これは紹介した方がいい」と判断したときは、押しつけずに選択肢として添える(よりそいホットライン 0120-279-338、差し迫っていれば119番)
- 気持ちの重さを確かめたいときは、尋問にならないよう、会話の中で自然に尋ねる(例: その気持ちはいつ頃から、どのくらい続いているか)
- 方法や手段の情報は出さない。軸・緊張・視点・腕などの分析の言葉、見出し、太字は使わない
- 最後は、続きを話してもらえる開かれた問いで終える。350字程度`;
    case "crisis":
      return `[寄り添いモード]
この相談には、強いつらさや、消えたい・死を考える気持ちがにじんでいる。分析や助言を急がず、まず一人の人として向き合う。
- 相談文を「」で引用して書き出さない(見出しのように引用し返すと機械的に響く)。自分の言葉で語りかけて始める
- 書き出しで注意喚起や相談窓口の案内から入らない。相手の言葉を受け止め、その奥にあるつらさを、本人の言葉に沿って決めつけずに言葉にする
- 打ち明けてくれたことを大切に受け取る。責めない、説教しない、「〜すべき」を並べない、安易に励まさない
- 何がそこまで追い詰めているのかを、ひとつだけ穏やかに尋ねてよい。死にたい気持ちがあるかを確かめるときは、遠回しにせず、でも柔らかく尋ねる
- 相談窓口は、突き放す形ではなく「ここで話し続けてもいいし、声で話せる場所もある」という選択肢として、本文の後半に自然に添える(よりそいホットライン 0120-279-338 は24時間・無料)
- すでに行動している、手段が手元にあるなど差し迫った危険がうかがえるときだけは、119番を短くはっきり伝える
- 方法や手段の情報は出さない。軸・緊張・視点・腕などの分析の言葉、見出し、太字の警告は使わない
- 最後は、続きを話してもらえるような開かれた問いで終える(はい/いいえで答えさせない)。全体は400字程度で、急がせない語り口にする`;
    case "medical_emergency":
      return `[緊急の可能性]
命に関わる急病の可能性がある症状。ためらわせないことが最優先だが、突き放さない。
- 相談文を「」で引用して書き出さない
- 不安な気持ちを一言受け止めてから、すぐに「今すぐ119番へ」と具体的に伝える。「何もなければそれでいい、確かめてもらうための電話」と、かけるハードルを下げる
- 自分で運転しない、楽な姿勢で待つ、近くの人に知らせる、電話で伝えること、を短く
- 軸・緊張・視点などの分析の言葉は使わない。300字程度に収める
- 最後は相手を気づかう一言で終える(次の一歩や問いの型にこだわらない)`;
    default:
      return null;
  }
}
