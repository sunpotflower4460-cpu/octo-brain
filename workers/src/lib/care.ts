// 繊細な相談の検出と、統合脳への「寄り添い方」の指示(LLM を使わない決定的な判定)。
// - crisis           : 希死念慮・自傷がにじむ相談
// - medical_emergency: 命に関わる急病の可能性がある症状
// 危険だと判定して案内だけを出すと「話を聞いてもらえなかった」と感じさせる。まず人として
// 向き合い、案内は自然な選択肢として添える。検出語はアプリ側(web/src/lib/crisis.ts)と揃える。

export type CareKind = "crisis" | "medical_emergency";

const CRISIS: RegExp[] = [
  /死にたい|しにたい|死のう|死んでしまいたい|消えたい|きえたい|消えてしまいたい|いなくなりたい/,
  /(全部|すべて|人生|何もかも|もう).{0,6}終わりにしたい|もう楽になりたい|楽になれる方法|生きるのが(つらい|辛い|しんどい|疲れた)|生きることに疲れ/,
  /自殺|自死|首を吊|首をつ|飛び降り|とびおり|練炭|OD(する|した|しよう)|オーバードーズ/,
  /リスカ|リストカット|自傷|自分を傷つけ|手首を切/,
  /生きていたくない|生きる意味がない|生きてる意味がない|もう限界で死/,
  /suicid|kill myself|end my life|self[- ]?harm|want to die/i,
];

const MEDICAL_EMERGENCY: RegExp[] = [
  /胸.{0,8}(締め付け|しめつけ|圧迫|激しく痛|強く痛)/,
  /(意識がない|意識が(ない|戻らない|もうろう)|呼びかけに反応しない|呼吸(をして|し)ていない|息をしていない)/,
  /(顔の片側|片側の(手足|腕|顔)).{0,8}(動かない|しびれ|麻痺|下が)|ろれつが回らない/,
  /(大量に|止まらない).{0,4}出血|血が止まらない|けいれん(が止まらない|している)/,
  /chest pain|can'?t breathe|not breathing|unconscious/i,
];

export function detectCare(input: string): CareKind | null {
  if (CRISIS.some((p) => p.test(input))) return "crisis";
  if (MEDICAL_EMERGENCY.some((p) => p.test(input))) return "medical_emergency";
  return null;
}

// 統合脳・深化・共鳴の user メッセージに添える指示。
export function careDirective(kind: CareKind | null): string | null {
  switch (kind) {
    case "crisis":
      return `[寄り添いモード]
この相談には、強いつらさや、消えたい・死を考える気持ちがにじんでいる。分析や助言を急がず、まず一人の人として向き合う。
- 相談文を「」で引用して書き出さない(見出しのように引用し返すと機械的に響く)。自分の言葉で語りかけて始める
- 書き出しで注意喚起や相談窓口の案内から入らない。相手の言葉を受け止め、その奥にあるつらさを、本人の言葉に沿って決めつけずに言葉にする
- 打ち明けてくれたことを大切に受け取る。責めない、説教しない、「〜すべき」を並べない、安易に励まさない
- 何がそこまで追い詰めているのかを、ひとつだけ穏やかに尋ねてよい。死にたい気持ちがあるかを確かめるときは、遠回しにせず、でも柔らかく尋ねる
- 相談窓口は、突き放す形ではなく「ここで話し続けてもいいし、声で話せる場所もある」という選択肢として、本文の後半に自然に添える(よりそいホットライン 0120-279-338 は24時間・無料)
- すでに行動している、手段が手元にあるなど差し迫った危険がうかがえるときだけは、119番を短くはっきり伝える
- 方法や手段の情報は出さない。軸・緊張・視点・腕などの分析の言葉、見出し、太字の警告は使わない
- 最後は、続きを話してもらえるような開かれた問いで終える(はい/いいえで答えさせない)。全体は400字程度で、急がせない語り口にする`;
    case "medical_emergency":
      return `[緊急の可能性]
命に関わる急病の可能性がある症状。ためらわせないことが最優先だが、突き放さない。
- 相談文を「」で引用して書き出さない
- 不安な気持ちを一言受け止めてから、すぐに「今すぐ119番へ」と具体的に伝える。「何もなければそれでいい、確かめてもらうための電話」と、かけるハードルを下げる
- 自分で運転しない、楽な姿勢で待つ、近くの人に知らせる、電話で伝えること、を短く
- 軸・緊張・視点などの分析の言葉は使わない。300字程度に収める
- 最後は相手を気づかう一言で終える(次の一歩や問いの型にこだわらない)`;
    default:
      return null;
  }
}
